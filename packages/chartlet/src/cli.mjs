#!/usr/bin/env node
// The `chartlet` command of the npm package: `render`, `inspect` and `stylesheet` with the
// bundled WebAssembly build, so no Rust toolchain is needed. It takes the options of the Rust CLI
// and writes the same output; PNG, fonts, watching and the preview stay with the Rust CLI.

import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { inspectChart, renderChartDetailed, stylesheet } from "./render.mjs";

const PROJECT_THEME = "chartlet.theme.json";
const BUNDLED_THEMES = ["light", "dark", "blueprint", "classic", "editorial"];
const STYLESHEET_HEADER = "/* generated by chartlet - do not edit */";
const RUST_ONLY = ["--scale", "--font", "--embed-font", "--watch", "--preview", "--port"];

const USAGE = `usage: chartlet render <spec.json|-> [--format svg|html] [-o <path>] [--id-prefix <prefix>] [--table details|visible] [--variant desktop|mobile|print|social] [--view <key> | --all-views] [--perspective <key>] [--theme <light|dark|blueprint|classic|editorial|theme.json>] [--size <preset>] [--manifest <path>] [--styles inline|external] [--focus | --no-focus] [--hooks] [--strict [--allow-warning <code>]...] [--diagnostics text|json [--advice]]
       chartlet inspect <spec.json|-> [--disable <code>]... [--strict] [--format text|json] [--diagnostics text|json]
       chartlet stylesheet [--types bar,time,...] [--no-common] [--breakpoints 420,...] | --common [--breakpoints 420,...]
PNG output, --font, --watch and --preview need the Rust CLI: cargo install chartlet`;

class Failure extends Error {
  constructor(message, code = "cli_error", path = null) {
    super(message);
    this.code = code;
    this.path = path;
  }

  get line() {
    return this.path == null ? this.message : `${this.code} at ${this.path}: ${this.message}`;
  }
}

const args = process.argv.slice(2);
const jsonDiagnostics =
  args.includes("--diagnostics=json") ||
  args.some((argument, index) => argument === "--diagnostics" && args[index + 1] === "json");
const report = { warnings: [], help: [] };

let failure;
try {
  run(args);
} catch (error) {
  if (!(error instanceof Failure)) {
    throw error;
  }
  failure = error;
}
if (jsonDiagnostics) {
  const document = {
    ok: !failure,
    error: failure ? { code: failure.code, path: failure.path, message: failure.message } : null,
    warnings: report.warnings,
  };
  if (report.help.length > 0) {
    document.help = report.help;
  }
  process.stderr.write(`${JSON.stringify(sortKeys(document))}\n`);
} else {
  if (failure) {
    process.stderr.write(`chartlet: ${failure.line}\n`);
  }
  for (const help of report.help) {
    process.stderr.write(`${helpLine(help)}\n`);
  }
}
if (failure) {
  process.exitCode = 1;
}

function run(argv) {
  const [command, ...rest] = argv;
  switch (command) {
    case "render":
      return render(rest);
    case "inspect":
      return inspect(rest);
    case "stylesheet":
      return writeStdout(sharedStylesheet(rest));
    case "-h":
    case "--help":
      return writeStdout(USAGE);
    default:
      throw new Failure(USAGE);
  }
}

function render(argv) {
  const [input, ...rest] = argv;
  if (input === "-h" || input === "--help") {
    return writeStdout(USAGE);
  }
  if (input === undefined) {
    throw new Failure(USAGE);
  }
  const options = { format: "svg", table: "details", allowWarnings: [] };
  let output;
  let manifestPath;
  let theme;
  let size;
  let advice = false;
  const next = argumentReader(rest);
  for (let argument = next(); argument !== undefined; argument = next()) {
    switch (argument) {
      case "--format": {
        const format = next();
        if (format === "png") {
          throw new Failure("--format png needs the Rust CLI: cargo install chartlet --features png");
        }
        options.format = oneOf(format, ["svg", "html"], "--format must be svg or html");
        break;
      }
      case "-o":
      case "--output":
        output = required(next(), "--output requires a path");
        break;
      case "--id-prefix":
        options.idPrefix = required(next(), "--id-prefix requires a value");
        break;
      case "--strict":
        options.strict = true;
        break;
      case "--allow-warning":
        options.allowWarnings.push(required(next(), "--allow-warning requires a warning code"));
        break;
      case "--table":
        options.table = oneOf(next(), ["details", "visible"], "--table must be details or visible");
        break;
      case "--variant":
        options.variant = oneOf(
          next(),
          ["desktop", "mobile", "print", "social"],
          "--variant must be desktop, mobile, print or social",
        );
        break;
      case "--view":
        options.view = required(next(), "--view requires the key of a view");
        break;
      case "--perspective":
        options.perspective = required(next(), "--perspective requires the key of a perspective");
        break;
      case "--theme":
        theme = required(
          next(),
          "--theme requires light, dark, blueprint, classic, editorial or the path of a theme file",
        );
        break;
      case "--size":
        size = required(next(), "--size requires a preset such as slide-16x9 or print-a4-landscape");
        break;
      case "--all-views":
        options.allViews = true;
        break;
      case "--advice":
        advice = true;
        break;
      case "--styles":
        options.styles = oneOf(next(), ["inline", "external"], "--styles must be inline or external");
        break;
      case "--focus":
        options.focus = true;
        break;
      case "--no-focus":
        options.focus = false;
        break;
      case "--hooks":
        options.hooks = true;
        break;
      case "--manifest":
        manifestPath = required(next(), "--manifest requires a path");
        options.manifest = true;
        break;
      case "--diagnostics":
        oneOf(next(), ["text", "json"], "--diagnostics must be text or json");
        break;
      case "--diagnostics=json":
      case "--diagnostics=text":
        break;
      case "-h":
      case "--help":
        return writeStdout(USAGE);
      default:
        throw unknownArgument(argument);
    }
  }
  // The project's own look applies unless another theme is asked for, as in the Rust CLI.
  theme ??= existsSync(PROJECT_THEME) ? PROJECT_THEME : undefined;
  if (theme !== undefined) {
    options.theme = BUNDLED_THEMES.includes(theme) ? theme : readTheme(theme);
  }
  let spec = readInput(input);
  if (size !== undefined) {
    let parsed;
    try {
      parsed = JSON.parse(spec);
    } catch (error) {
      throw new Failure(`could not read the specification: ${error.message}`);
    }
    if (parsed && typeof parsed === "object" && !Array.isArray(parsed)) {
      parsed.size = size;
    }
    spec = JSON.stringify(parsed);
  }

  const result = renderChartDetailed(spec, { ...options, advice });
  report.warnings.push(...result.warnings);
  if (!jsonDiagnostics) {
    for (const { code, path, message } of result.warnings) {
      process.stderr.write(`warning[${code}] at ${path}: ${message}\n`);
    }
  }
  if (!result.ok) {
    const { code, path, message } = result.error;
    throw new Failure(message, code, path);
  }
  report.help.push(...(result.help ?? []));
  if (output === undefined) {
    writeStdout(result.content);
  } else {
    writeFile(output, result.content);
  }
  if (manifestPath !== undefined) {
    writeFile(manifestPath, `${JSON.stringify(result.manifest)}\n`);
  }
}

function inspect(argv) {
  const [input, ...rest] = argv;
  if (input === "-h" || input === "--help") {
    return writeStdout(USAGE);
  }
  if (input === undefined) {
    throw new Failure(USAGE);
  }
  const disable = [];
  let strict = false;
  let json = false;
  const next = argumentReader(rest);
  for (let argument = next(); argument !== undefined; argument = next()) {
    switch (argument) {
      case "--disable":
        disable.push(required(next(), "--disable requires an inspection code"));
        break;
      case "--strict":
        strict = true;
        break;
      case "--format":
        json = oneOf(next(), ["text", "json"], "--format must be text or json") === "json";
        break;
      case "--diagnostics":
        oneOf(next(), ["text", "json"], "--diagnostics must be text or json");
        break;
      case "--diagnostics=json":
      case "--diagnostics=text":
        break;
      case "-h":
      case "--help":
        return writeStdout(USAGE);
      default:
        throw unknownArgument(argument);
    }
  }
  const result = inspectChart(readInput(input), { disable });
  if (!result.ok) {
    const { code, path, message } = result.error;
    throw new Failure(message, code, path);
  }
  const { findings } = result;
  const text = json
    ? JSON.stringify({ findings })
    : findings
        .map(
          ({ severity, code, path, message, hint }) =>
            `${severity}[${code}] at ${path}: ${message}; ${hint}`,
        )
        .join("\n");
  if (text !== "") {
    writeStdout(text);
  }
  const gaps = findings.filter((finding) => finding.severity === "gap").length;
  if (strict && gaps > 0) {
    throw new Failure(`strict mode rejected ${gaps} gap(s)`, "strict_inspections");
  }
}

function sharedStylesheet(argv) {
  let types;
  let common = true;
  let commonOnly = false;
  let breakpoints = [];
  const next = argumentReader(argv);
  for (let argument = next(); argument !== undefined; argument = next()) {
    switch (argument) {
      case "--breakpoints": {
        const widths = required(next(), "--breakpoints requires a list such as 420,560");
        breakpoints = widths.split(",").map((width) => {
          if (!/^\d+$/.test(width.trim())) {
            throw new Failure(`--breakpoints takes widths in pixels, not ${JSON.stringify(width)}`);
          }
          return Number(width.trim());
        });
        break;
      }
      case "--types":
        types = required(next(), "--types requires a list such as bar,time")
          .split(",")
          .map((name) => name.trim());
        break;
      case "--no-common":
        common = false;
        break;
      case "--common":
        commonOnly = true;
        break;
      default:
        throw unknownArgument(argument);
    }
  }
  if (commonOnly && (types !== undefined || !common)) {
    throw new Failure("--common takes neither --types nor --no-common");
  }
  let css;
  try {
    css = stylesheet({ types: commonOnly ? [] : types, common, breakpoints });
  } catch (error) {
    throw new Failure(error.message.replace(/^chartlet: /, ""));
  }
  // The file lands in a project's source tree, where formatters would treat it as hand-written.
  return `${STYLESHEET_HEADER}\n${css}`;
}

function argumentReader(argv) {
  let index = 0;
  return () => argv[index++];
}

function required(value, message) {
  if (value === undefined) {
    throw new Failure(message);
  }
  return value;
}

function oneOf(value, allowed, message) {
  if (!allowed.includes(value)) {
    throw new Failure(message);
  }
  return value;
}

function unknownArgument(argument) {
  if (RUST_ONLY.includes(argument)) {
    return new Failure(`${argument} needs the Rust CLI: cargo install chartlet`);
  }
  return new Failure(`unknown argument ${JSON.stringify(argument)}\n\n${USAGE}`);
}

function readInput(input) {
  if (input === "-") {
    try {
      return readFileSync(0, "utf8");
    } catch (error) {
      throw new Failure(`could not read stdin: ${error.message}`);
    }
  }
  return readText(input);
}

function readTheme(path) {
  try {
    return JSON.parse(readText(path));
  } catch (error) {
    if (error instanceof Failure) {
      throw error;
    }
    throw new Failure(`could not read ${path}: ${error.message}`);
  }
}

function readText(path) {
  try {
    return readFileSync(path, "utf8");
  } catch (error) {
    throw new Failure(`could not read ${path}: ${error.message}`);
  }
}

function writeFile(path, content) {
  try {
    writeFileSync(path, content);
  } catch (error) {
    throw new Failure(`could not write ${path}: ${error.message}`);
  }
}

function writeStdout(content) {
  process.stdout.write(`${content}\n`);
}

// Object keys in alphabetical order, as the Rust CLI writes its diagnostics.
function sortKeys(value) {
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys(value[key])]),
    );
  }
  return value;
}

// One help entry as text, as the Rust CLI writes it: where to look, and each remedy.
function helpLine(help) {
  let line = `help[${help.code}] at ${help.field}: see ${help.docs}`;
  for (const remedy of help.remedies) {
    let patch = "";
    if (remedy.patch.length > 0) {
      const operations = remedy.patch.map(
        (operation) =>
          `${JSON.stringify(operation.op)} ${JSON.stringify(operation.path)} = ${JSON.stringify(operation.value)}`,
      );
      const checked = remedy.resolves ? "checked: resolves it" : "checked: does not resolve it";
      patch = ` [${checked}; patch: ${operations.join(", ")}]`;
    }
    line += `\n  - ${remedy.summary}${patch}`;
  }
  return line;
}

import json
import subprocess
import threading
import warnings

import pytest

import chartlet
from chartlet._fence import fence_settings

from conftest import EXAMPLES

# Some examples warn on purpose; the warnings test below records them itself.
pytestmark = pytest.mark.filterwarnings("ignore::chartlet.ChartletWarning")

SPECS = sorted(EXAMPLES.glob("*.json"))


@pytest.mark.parametrize("spec", SPECS, ids=[spec.stem for spec in SPECS])
def test_every_example_matches_the_cli(spec, cli_render):
    assert chartlet.render(spec) == cli_render(spec)
    assert chartlet.render(spec, format="html") == cli_render(spec, "--format", "html")
    if "mobile" in json.loads(spec.read_text(encoding="utf-8")):
        assert chartlet.render(spec, variant="mobile") == cli_render(spec, "--variant", "mobile")


@pytest.mark.parametrize(
    ("example", "options", "arguments"),
    [
        ("monthly-revenue", {"variant": "print"}, ["--variant", "print"]),
        ("monthly-revenue", {"variant": "social"}, ["--variant", "social"]),
        ("monthly-revenue", {"theme": "dark"}, ["--theme", "dark"]),
        (
            "monthly-revenue",
            {"format": "html", "table": "visible", "id_prefix": "revenue"},
            ["--format", "html", "--table", "visible", "--id-prefix", "revenue"],
        ),
        (
            "monthly-revenue",
            {"format": "html", "styles": "external", "hooks": True},
            ["--format", "html", "--styles", "external", "--hooks"],
        ),
        ("api-environments", {"view": "production"}, ["--view", "production"]),
        (
            "api-environments",
            {"format": "html", "all_views": True},
            ["--format", "html", "--all-views"],
        ),
        ("booking-deployment", {"view": "logical"}, ["--view", "logical"]),
        ("service-perspectives", {"perspective": "debt"}, ["--perspective", "debt"]),
        (
            "booking-deployment",
            {"format": "html", "focus": False},
            ["--format", "html", "--no-focus"],
        ),
    ],
)
def test_options_match_the_cli(example, options, arguments, cli_render):
    spec = EXAMPLES / f"{example}.json"
    assert chartlet.render(spec, **options) == cli_render(spec, *arguments)


def test_a_mapping_and_json_text_render_like_the_file():
    spec = EXAMPLES / "monthly-revenue.json"
    text = spec.read_text(encoding="utf-8")
    assert chartlet.render(json.loads(text)) == chartlet.render(spec)
    assert chartlet.render(text) == chartlet.render(spec)


def test_the_stylesheet_matches_the_cli(cli):
    for arguments, options in [([], {}), (["--types", "bar,time"], {"types": ["bar", "time"]})]:
        printed = subprocess.run(
            [cli, "stylesheet", *arguments], check=True, capture_output=True, text=True
        ).stdout
        # The CLI writes a header comment above the same rules.
        assert printed == f"/* generated by chartlet - do not edit */\n{chartlet.stylesheet(**options)}\n"


def test_an_invalid_specification_raises_with_its_diagnostic():
    with pytest.raises(chartlet.ChartletError) as raised:
        chartlet.render({"schemaVersion": 1, "type": "bar", "title": "Empty", "data": "none"})
    assert raised.value.code == "invalid_spec"
    assert raised.value.path is None or raised.value.path.startswith("/")
    assert isinstance(raised.value, ValueError)


def test_an_invalid_option_raises():
    with pytest.raises(chartlet.ChartletError, match="format must be svg or html"):
        chartlet.render(EXAMPLES / "monthly-revenue.json", format="png")


DENSE = {
    "schemaVersion": 1,
    "type": "bar",
    "title": "Dense",
    "width": 320,
    "data": [{"label": f"Category number {index}", "value": index} for index in range(40)],
}


def test_warnings_are_issued_and_strict_rejects_them():
    rendered = chartlet.render_detailed(DENSE)
    assert rendered.warnings, "the dense chart should warn"
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        chartlet.render(DENSE)
    assert [warning.category for warning in caught] == [chartlet.ChartletWarning] * len(
        rendered.warnings
    )
    assert caught[0].message.diagnostic == rendered.warnings[0]
    with pytest.raises(chartlet.ChartletError) as raised:
        chartlet.render(DENSE, strict=True)
    assert raised.value.code == "strict_warnings"
    assert raised.value.warnings == rendered.warnings
    codes = sorted({warning.code for warning in rendered.warnings})
    assert chartlet.render_detailed(DENSE, strict=True, allow_warnings=codes).warnings


def test_render_detailed_returns_what_was_asked_for():
    spec = EXAMPLES / "monthly-revenue.json"
    rendered = chartlet.render_detailed(spec, format="html", manifest=True, alternative=True)
    assert rendered.content == chartlet.render(spec, format="html")
    assert rendered.style_hashes and rendered.style_hashes[0].startswith("'sha256-")
    assert rendered.manifest["chartlet"] == chartlet.__version__
    assert rendered.alternative["table"]["columns"]


def test_a_chart_shows_its_html_figure_in_jupyter():
    spec = EXAMPLES / "monthly-revenue.json"
    assert chartlet.Chart(spec)._repr_html_() == chartlet.render(spec, format="html")
    assert chartlet.Chart(spec, id_prefix="r", table="visible")._repr_html_() == chartlet.render(
        spec, format="html", id_prefix="r", table="visible"
    )


def test_threads_share_the_renderer():
    spec = EXAMPLES / "monthly-revenue.json"
    expected = chartlet.render(spec)
    results = []
    threads = [
        threading.Thread(target=lambda: results.append(chartlet.render(spec))) for _ in range(8)
    ]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    assert results == [expected] * 8


def test_fence_settings():
    assert fence_settings("") == {}
    assert fence_settings(' id=revenue view="the checkout" perspective=\'a b\' ') == {
        "id_prefix": "revenue",
        "view": "the checkout",
        "perspective": "a b",
    }
    with pytest.raises(ValueError, match='unknown fence setting "size"; the settings are id'):
        fence_settings("size=large")
    with pytest.raises(ValueError, match="cannot read"):
        fence_settings("revenue")
